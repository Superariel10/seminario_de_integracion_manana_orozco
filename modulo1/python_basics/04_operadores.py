# Operadores Matematicos

a = 15
b = 20
print ("Suma")
print(a,"+", b, "=", a+b)
print ("Resta")
print(a,"-", b, "=", a-b)
print ("Division")
print(a,"/", b, "=", a/b)
print ("Multiplicacion")
print(a,"*", b, "=", a*b)
print ("Potencia")
print(a,"**", b, "=", a**b)
print ("Division Entera")
print(a,"//", b, "=", a//b)
print ("Modulo")
print(a,"%", b, "=", a%b)
print ("Operadores de Asignacion")
print("=========================")
n=10
